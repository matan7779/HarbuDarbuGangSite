create or replace function public.hdg_close_night(p_group_key text, p_state jsonb)
returns void
language plpgsql
security definer
set search_path=public
as $$
begin
  if not exists(select 1 from public.hdg_groups where group_key=p_group_key) then
    raise exception 'Invalid group access';
  end if;
  insert into public.hdg_nights(group_key,night_date,players,games,rebuys,cashout)
  values(
    p_group_key,
    coalesce(p_state->>'date',''),
    coalesce(p_state->'players','[]'::jsonb),
    coalesce(p_state->'games','[]'::jsonb),
    coalesce(p_state->'rebuys','{}'::jsonb),
    coalesce(p_state->'cashout','{}'::jsonb)
  );
  delete from public.hdg_live
  where group_key=p_group_key and room_code=upper(coalesce(p_state->>'room',''));
end;
$$;

create or replace function public.hdg_get_old_nights(p_group_key text)
returns table(
  id bigint,
  night_date text,
  players jsonb,
  games jsonb,
  rebuys jsonb,
  cashout jsonb,
  created_at timestamptz
)
language plpgsql
security definer
set search_path=public
as $$
begin
  if not exists(select 1 from public.hdg_groups where group_key=p_group_key) then
    raise exception 'Invalid group access';
  end if;
  return query
  select n.id,n.night_date,n.players,n.games,n.rebuys,n.cashout,n.created_at
  from public.hdg_nights n
  where n.group_key=p_group_key
  order by n.created_at desc;
end;
$$;

create or replace function public.hdg_delete_night(p_group_key text, p_night_id bigint)
returns void
language plpgsql
security definer
set search_path=public
as $$
begin
  if not exists(select 1 from public.hdg_groups where group_key=p_group_key) then
    raise exception 'Invalid group access';
  end if;
  delete from public.hdg_nights
  where group_key=p_group_key and id=p_night_id;
end;
$$;

